"""Сервисные правила ролевых ограничений и проверок доступа."""

from apps.accounts.models import User, UserRole


def is_admin(user: User) -> bool:
    """Проверяет, что пользователь имеет административную роль.

    Контекст использования:
    - применяется в views/сервисах для допуска к административным операциям.

    Параметры:
    - `user`: проверяемый пользователь.

    Возвращает:
    - `True`, если роль `admin` или `superadmin`, иначе `False`.

    Исключения и особые случаи:
    - для анонимного пользователя ожидается `False`.

    Побочные эффекты:
    - отсутствуют.
    """

    return bool(user and user.is_authenticated and user.role in {UserRole.ADMIN, UserRole.SUPERADMIN})


def is_superadmin(user: User) -> bool:
    """Проверяет, что пользователь является назначенным или главным супер-админом.

    Контекст использования:
    - применяется при доступе к глобальным настройкам и LLM-параметрам.

    Параметры:
    - `user`: проверяемый пользователь.

    Возвращает:
    - `True`, если роль `superadmin`, иначе `False`.

    Исключения и особые случаи:
    - отсутствуют.

    Побочные эффекты:
    - отсутствуют.
    """

    return bool(user and user.is_authenticated and user.role == UserRole.SUPERADMIN)


def is_primary_superadmin(user: User) -> bool:
    """Проверяет, что пользователь является главным супер-администратором.

    Контекст использования:
    - используется для операций создания администраторов и выдачи superadmin-прав.

    Параметры:
    - `user`: проверяемый пользователь.

    Возвращает:
    - `True`, если у пользователя роль `superadmin` и флаг `is_primary_superadmin=True`.

    Исключения и особые случаи:
    - отсутствуют.

    Побочные эффекты:
    - отсутствуют.
    """

    return bool(is_superadmin(user) and user.is_primary_superadmin)


def can_create_admin(actor: User) -> bool:
    """Определяет право создать нового администратора.

    Контекст использования:
    - применяется в сервисах управления пользователями и ролями.

    Параметры:
    - `actor`: пользователь, выполняющий действие.

    Возвращает:
    - `True` только для главного супер-администратора.

    Исключения и особые случаи:
    - отсутствуют.

    Побочные эффекты:
    - отсутствуют.
    """

    return is_primary_superadmin(actor)


def can_assign_superadmin(actor: User) -> bool:
    """Определяет право назначать или отзывать superadmin-роль.

    Контекст использования:
    - используется в административном сервисе управления ролями.

    Параметры:
    - `actor`: пользователь-инициатор операции.

    Возвращает:
    - `True` только для главного супер-администратора.

    Исключения и особые случаи:
    - отсутствуют.

    Побочные эффекты:
    - отсутствуют.
    """

    return is_primary_superadmin(actor)
