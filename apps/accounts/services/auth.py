"""Сервисные функции аутентификации, включая ограничение частоты логина."""

from django.core.cache import cache


def login_attempts_cache_key(email: str) -> str:
    """Строит ключ кэша для счётчика попыток входа по email.

    Контекст использования:
    - используется при throttling входа для защиты от частых попыток.

    Параметры:
    - `email`: email пользователя, использованный в форме входа.

    Возвращает:
    - строковый ключ кэша.

    Исключения и особые случаи:
    - если email пустой, всё равно формируется стабильный ключ.

    Побочные эффекты:
    - отсутствуют.
    """

    return f"auth:login_attempts:{(email or '').strip().lower()}"


def is_login_throttled(email: str, limit: int = 5) -> bool:
    """Проверяет, превышен ли лимит частоты попыток входа.

    Контекст использования:
    - вызывается перед аутентификацией на странице логина.

    Параметры:
    - `email`: email из формы входа;
    - `limit`: максимально допустимое число ошибок в окне throttling.

    Возвращает:
    - `True`, если лимит достигнут; иначе `False`.

    Исключения и особые случаи:
    - при отсутствии ключа в кэше трактуется как `0` попыток.

    Побочные эффекты:
    - отсутствуют.
    """

    attempts = int(cache.get(login_attempts_cache_key(email), 0))
    return attempts >= limit


def register_failed_login_attempt(email: str, window_seconds: int = 900) -> None:
    """Увеличивает счётчик неудачных входов в заданном временном окне.

    Контекст использования:
    - вызывается после неуспешной попытки логина.

    Параметры:
    - `email`: email из формы входа;
    - `window_seconds`: окно хранения счётчика в секундах.

    Возвращает:
    - ничего не возвращает.

    Исключения и особые случаи:
    - отсутствуют.

    Побочные эффекты:
    - записывает/обновляет счётчик в кэше.
    """

    key = login_attempts_cache_key(email)
    cache.add(key, 0, timeout=window_seconds)
    cache.incr(key)


def reset_login_attempts(email: str) -> None:
    """Сбрасывает счётчик неудачных попыток после успешного входа.

    Контекст использования:
    - вызывается сразу после успешной аутентификации пользователя.

    Параметры:
    - `email`: email пользователя.

    Возвращает:
    - ничего не возвращает.

    Исключения и особые случаи:
    - если ключ отсутствует, удаление безопасно и не приводит к ошибке.

    Побочные эффекты:
    - удаляет ключ счётчика из кэша.
    """

    cache.delete(login_attempts_cache_key(email))
