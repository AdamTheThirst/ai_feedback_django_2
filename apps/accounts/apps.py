"""Конфигурация Django-приложения accounts."""

from django.apps import AppConfig


class AccountsConfig(AppConfig):
    """Описывает базовую конфигурацию приложения .

    Контекст использования:
    - применяется Django при инициализации реестра приложений;
    - задаёт  и  для административного отображения.

    Параметры:
    - класс не принимает параметров напрямую; атрибуты используются фреймворком.

    Возвращает:
    - экземпляр класса конфигурации приложения, создаваемый Django автоматически.

    Исключения и особые случаи:
    - в текущей итерации не ожидаются, так как конфигурация статична.

    Побочные эффекты:
    - регистрирует приложение в проекте при старте Django.
    """

    default_auto_field = "django.db.models.BigAutoField"
    name = "apps.accounts"
    verbose_name = "accounts"
