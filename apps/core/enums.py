"""Перечисления доменных статусов и причин для диалогов и анализа."""

from django.db import models


class DialogStatus(models.TextChoices):
    """Описывает жизненные статусы игровой сессии диалога.

    Контекст использования:
    - применяется в модели `DialogSession` для явного контроля переходов состояния;
    - используется в сервисах и проверках бизнес-логики, чтобы исключить магические строки.

    Параметры:
    - параметры не передаются вручную; значения статусов определены на уровне перечисления.

    Возвращает:
    - строковое значение статуса через стандартный интерфейс `TextChoices`.

    Исключения и особые случаи:
    - некорректное значение не должно попадать в БД благодаря `choices`.

    Побочные эффекты:
    - отсутствуют; перечисление используется как справочник допустимых значений.
    """

    ACTIVE = "active", "Активен"
    FINISHED = "finished", "Завершён"
    ABORTED = "aborted", "Прерван"
    ANALYSIS_SKIPPED = "analysis_skipped", "Анализ пропущен"


class DialogEndedReason(models.TextChoices):
    """Описывает причины завершения диалога.

    Контекст использования:
    - хранится в `DialogSession.ended_reason` для диагностики способа завершения;
    - используется в аналитике продукта и в последующем отображении истории пользователя.

    Параметры:
    - значения задаются предопределёнными элементами перечисления.

    Возвращает:
    - строковый код причины завершения.

    Исключения и особые случаи:
    - если диалог ещё активен, причина может оставаться пустой.

    Побочные эффекты:
    - отсутствуют.
    """

    MANUAL_FEEDBACK = "manual_feedback", "Кнопка обратной связи"
    TIMEOUT = "timeout", "Таймер истёк"
    PAGE_LEAVE = "page_leave", "Покинул страницу"
    INACTIVE_TIMEOUT = "inactive_timeout", "Серверный таймаут неактивности"
    NO_USER_MESSAGES = "no_user_messages", "Нет пользовательских реплик"


class AnalysisRunStatus(models.TextChoices):
    """Описывает статусы запуска аналитики для диалога.

    Контекст использования:
    - применяется в `AnalysisRun.status` для контроля технического состояния анализа;
    - помогает корректно обрабатывать ретраи, ошибки и финальные состояния.

    Параметры:
    - используются фиксированные значения перечисления.

    Возвращает:
    - строковый код технического статуса анализа.

    Исключения и особые случаи:
    - невалидные состояния блокируются уровнем `choices`.

    Побочные эффекты:
    - отсутствуют.
    """

    PENDING = "pending", "Ожидает запуска"
    RUNNING = "running", "Выполняется"
    COMPLETED = "completed", "Завершён успешно"
    FAILED = "failed", "Завершён с ошибкой"
    SKIPPED = "skipped", "Пропущен"
