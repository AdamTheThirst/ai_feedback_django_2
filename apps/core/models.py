"""Базовые абстрактные модели для повторного использования в предметных приложениях."""

import uuid

from django.db import models


class TimestampedModel(models.Model):
    """Добавляет служебные поля времени создания и обновления записи.

    Контекст использования:
    - служит базовым абстрактным классом для доменных сущностей проекта;
    - обеспечивает единообразные поля `created_at` и `updated_at` в разных модулях.

    Параметры:
    - входные параметры не передаются; поля обновляются ORM автоматически.

    Возвращает:
    - экземпляры наследников с заполненными временными метками.

    Исключения и особые случаи:
    - особые случаи не предусмотрены, кроме стандартного поведения ORM.

    Побочные эффекты:
    - при каждом сохранении обновляется `updated_at`.
    """

    created_at = models.DateTimeField(auto_now_add=True, verbose_name="Создано")
    updated_at = models.DateTimeField(auto_now=True, verbose_name="Обновлено")

    class Meta:
        """Мета-настройки абстрактной модели времени."""

        abstract = True


class ArchivableModel(models.Model):
    """Добавляет поддержку мягкого архивирования мастер-данных.

    Контекст использования:
    - применяется для сущностей, которые нельзя жёстко удалять без риска поломки истории;
    - хранит флаг архивности и момент архивирования.

    Параметры:
    - параметры не передаются напрямую; поля управляются сервисной логикой.

    Возвращает:
    - экземпляры наследников с признаками архивного состояния.

    Исключения и особые случаи:
    - если запись не архивирована, `archived_at` остаётся `NULL`.

    Побочные эффекты:
    - изменение `is_archived` может скрывать запись из пользовательских списков.
    """

    is_archived = models.BooleanField(default=False, verbose_name="В архиве")
    archived_at = models.DateTimeField(null=True, blank=True, verbose_name="Архивировано")

    class Meta:
        """Мета-настройки абстрактной модели архивирования."""

        abstract = True


class PublicIdModel(models.Model):
    """Добавляет внешний стабильный UUID-идентификатор сущности.

    Контекст использования:
    - используется в моделях, где необходим безопасный внешний идентификатор;
    - снижает зависимость публичных ссылок от внутреннего числового `id`.

    Параметры:
    - генерация `public_id` выполняется автоматически через `uuid4`.

    Возвращает:
    - экземпляры наследников с уникальным UUID в поле `public_id`.

    Исключения и особые случаи:
    - коллизии UUID статистически маловероятны и контролируются уникальным ограничением.

    Побочные эффекты:
    - отсутствуют.
    """

    public_id = models.UUIDField(default=uuid.uuid4, unique=True, editable=False, verbose_name="Публичный ID")

    class Meta:
        """Мета-настройки абстрактной модели публичного идентификатора."""

        abstract = True
