"""Template tags для безопасного рендера HTML-фрагментов аналитики."""

from html import escape
from html.parser import HTMLParser

from django import template
from django.utils.safestring import mark_safe

register = template.Library()


class AllowedAnalysisHtmlParser(HTMLParser):
    """Оставляет только разрешённые теги и экранирует остальной HTML.

    Контекст использования:
    - применяется при рендере текста аналитики от LLM в пользовательской карточке;
    - защищает от XSS, оставляя только согласованный набор простых тегов форматирования.

    Параметры:
    - использует стандартный интерфейс `HTMLParser`.

    Возвращает:
    - формирует внутренний буфер безопасной HTML-строки.

    Исключения и особые случаи:
    - атрибуты тегов полностью игнорируются;
    - неподдерживаемые теги выводятся как экранированный текст.

    Побочные эффекты:
    - отсутствуют.
    """

    allowed_tags = {"b", "i", "li", "p", "ul", "br", "ol"}

    def __init__(self) -> None:
        """Инициализирует парсер и буфер результата.

        Контекст использования:
        - вызывается для каждого рендера фильтра `render_analysis_html`.

        Параметры:
        - отсутствуют.

        Возвращает:
        - ничего не возвращает.

        Исключения и особые случаи:
        - отсутствуют.

        Побочные эффекты:
        - создаёт пустой буфер сегментов HTML.
        """

        super().__init__()
        self.chunks: list[str] = []

    def handle_starttag(self, tag: str, attrs) -> None:
        """Добавляет открывающий тег, если он разрешён.

        Контекст использования:
        - вызывается парсером при встрече открывающего тега.

        Параметры:
        - `tag`: имя тега;
        - `attrs`: список атрибутов (игнорируется).

        Возвращает:
        - ничего не возвращает.

        Исключения и особые случаи:
        - неразрешённые теги экранируются и выводятся как текст.

        Побочные эффекты:
        - добавляет сегмент в буфер результата.
        """

        _ = attrs
        if tag in self.allowed_tags:
            self.chunks.append(f"<{tag}>")
        else:
            self.chunks.append(escape(f"<{tag}>"))

    def handle_endtag(self, tag: str) -> None:
        """Добавляет закрывающий тег, если он разрешён.

        Контекст использования:
        - вызывается парсером при встрече закрывающего тега.

        Параметры:
        - `tag`: имя тега.

        Возвращает:
        - ничего не возвращает.

        Исключения и особые случаи:
        - неразрешённые теги экранируются и выводятся как текст.

        Побочные эффекты:
        - добавляет сегмент в буфер результата.
        """

        if tag in self.allowed_tags:
            self.chunks.append(f"</{tag}>")
        else:
            self.chunks.append(escape(f"</{tag}>"))

    def handle_data(self, data: str) -> None:
        """Экранирует текстовые данные внутри HTML.

        Контекст использования:
        - вызывается для любого текстового содержимого ответа LLM.

        Параметры:
        - `data`: сырой текстовый фрагмент.

        Возвращает:
        - ничего не возвращает.

        Исключения и особые случаи:
        - отсутствуют.

        Побочные эффекты:
        - добавляет экранированный текст в буфер результата.
        """

        self.chunks.append(escape(data))

    def get_html(self) -> str:
        """Возвращает итоговую безопасную HTML-строку.

        Контекст использования:
        - вызывается фильтром после завершения парсинга.

        Параметры:
        - отсутствуют.

        Возвращает:
        - объединённую строку из буфера `chunks`.

        Исключения и особые случаи:
        - отсутствуют.

        Побочные эффекты:
        - отсутствуют.
        """

        return "".join(self.chunks)


@register.filter(name="render_analysis_html")
def render_analysis_html(value: str) -> str:
    """Преобразует текст аналитики в безопасный HTML с белым списком тегов.

    Контекст использования:
    - используется в шаблоне `dialogs/results.html` для рендера карточек анализа.

    Параметры:
    - `value`: исходный текст анализа от LLM.

    Возвращает:
    - safe-строку для шаблона Django.

    Исключения и особые случаи:
    - если вход пустой, возвращается пустая строка.

    Побочные эффекты:
    - отсутствуют.
    """

    raw = value or ""
    parser = AllowedAnalysisHtmlParser()
    parser.feed(raw)
    parser.close()
    return mark_safe(parser.get_html())
